"""Generate runner/dkc1_coop_callers.h: which generated functions asking
Player_GetIndexOffset ($80:9B9C) want the Kong nearest to the asking sprite
instead of the leader (categories A and C of COOP_MAP_sites.csv, minus the
mine cart, which follows its leader).

usage: python callers.py <COOP_MAP_sites.csv> <Routine_Macros_DKC1.asm> <recomp_v12 dir> <out.h>
"""
import csv
import glob
import re
import sys

sites_csv, asm, cfg_dir, out = sys.argv[1:5]
lines = open(asm, encoding="latin-1").read().splitlines()

# v1.0 address of every label: CODE_XXXXXX names, or the ";$XXXXXX" comment
# that follows named routines (DKC1_*_Main).
label_addr = {}
for i, l in enumerate(lines):
    m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):", l)
    if not m:
        continue
    name = m.group(1)
    a = re.match(r"^(?:CODE|ADDR)_([0-9A-F]{6})$", name)
    if a:
        label_addr[name] = int(a.group(1), 16)
        continue
    for j in range(i + 1, min(i + 3, len(lines))):
        c = re.match(r"^\s*;\$([0-9A-F]{6})", lines[j])
        if c:
            label_addr[name] = int(c.group(1), 16)
            break

# Generated functions: name (v1.0 label), v1.2 start/end -> v1.0 range.
funcs = []
for cfg in glob.glob(cfg_dir + "/*.cfg"):
    for l in open(cfg):
        m = re.match(r"^func (\S+) ([0-9A-F]+) end:([0-9A-F]+)", l)
        if not m or m.group(1) not in label_addr:
            continue
        start10 = label_addr[m.group(1)]
        size = int(m.group(3), 16) - int(m.group(2), 16)
        if size > 0:
            funcs.append((start10, start10 + size, m.group(1)))

def enclosing(addr):
    best = None
    for a, b, n in funcs:
        if a <= addr < b and (best is None or a > best[0]):
            best = (a, b, n)
    return best[2] if best else None

want = {}
unresolved = []
for row in csv.DictReader(open(sites_csv, encoding="utf-8")):
    if row["tipo"] != "player_slot_809B9C" or row["categoria"] not in ("A", "C"):
        continue
    if "carrinho" in row["nota"]:
        continue  # the mine cart follows its leader
    if row["rotina"] == "CODE_BF8463":
        continue  # run by the sprite loop itself, not by an asking sprite
    addr = label_addr.get(row["rotina"])
    fn = enclosing(addr) if addr is not None else None
    if not fn:
        unresolved.append(row["rotina"])
        continue
    want.setdefault(fn, set()).add(row["categoria"] + ": " + row["nota"])

with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/coopmap/callers.py from COOP_MAP_sites.csv: generated\n"
            " * functions whose \"which slot is the player\" question ($80:9B9C) is about\n"
            " * the Kong interacting with the asking sprite (aim, proximity, ropes, barrel\n"
            " * cannons...) rather than the leader. Do not edit by hand. */\n")
    f.write("static const char *const kCoopNearestKongCallers[] = {\n")
    for fn in sorted(want):
        f.write(f'  "{fn}_M0X0", /* {"; ".join(sorted(want[fn]))} */\n')
    f.write("};\n")
print(len(want), "functions;", "unresolved:", unresolved)
